package main

import (
	"bytes"
	"context"
	"encoding/json"
	"flag"
	"fmt"
	"os"
	"path/filepath"
	"regexp"
	"strings"

	"github.com/oklog/ulid/v2"
	openfgav1 "github.com/openfga/api/proto/openfga/v1"
	"github.com/openfga/language/pkg/go/transformer"
	"github.com/openfga/openfga/pkg/typesystem"
	"google.golang.org/protobuf/encoding/protojson"
	"google.golang.org/protobuf/proto"

	"github.com/juju/juju/domain/access/authorisation"
)

const (
	sourceDir   = "domain/access/authorisation"
	seedFile    = "domain/schema/controller/sql/0017-user-permission.sql"
	beginMarker = "-- BEGIN GENERATED AUTHORISATION MODEL\n"
	endMarker   = "-- END GENERATED AUTHORISATION MODEL\n"
)

func main() {
	root := flag.String("root", ".", "Juju repository root")
	check := flag.Bool("check", false, "check generated SQL without writing it")
	flag.Parse()
	if err := run(*root, *check); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}

func run(root string, check bool) error {
	source := filepath.Join(sourceDir, authorisation.ModelFile)
	model, err := loadModel(filepath.Join(root, source))
	if err != nil {
		return err
	}

	path := filepath.Join(root, seedFile)
	previous, err := os.ReadFile(path)
	if err != nil {
		return err
	}
	if bytes.Count(previous, []byte(beginMarker)) != 1 || bytes.Count(previous, []byte(endMarker)) != 1 {
		return fmt.Errorf("%s must contain exactly one generated model block", path)
	}
	start := bytes.Index(previous, []byte(beginMarker)) + len(beginMarker)
	end := bytes.Index(previous, []byte(endMarker))
	if end < start {
		return fmt.Errorf("invalid generated model block in %s", path)
	}
	if err := checkImmutableModel(previous[start:end], model); err != nil {
		return err
	}

	data, err := canonicalJSON(model)
	if err != nil {
		return err
	}
	block := fmt.Sprintf("-- Code generated by generate/authorisation. DO NOT EDIT.\n-- Source: %s\nINSERT INTO openfga_authorization_model (store_id, model_id, model)\nVALUES ('%s', '%s', '%s');\n",
		source, authorisation.StoreID, model.Id, strings.ReplaceAll(string(data), "'", "''"))
	generated := append([]byte(nil), previous[:start]...)
	generated = append(generated, block...)
	generated = append(generated, previous[end:]...)
	if bytes.Equal(previous, generated) {
		return nil
	}
	if check {
		return fmt.Errorf("%s is stale; run go generate ./domain/access/authorisation", seedFile)
	}
	return replaceFile(path, generated)
}

func loadModel(path string) (*openfgav1.AuthorizationModel, error) {
	for _, id := range []string{authorisation.StoreID, authorisation.ModelID} {
		if _, err := ulid.ParseStrict(id); err != nil {
			return nil, fmt.Errorf("invalid authorisation ID %q: %w", id, err)
		}
	}
	source, err := os.ReadFile(path)
	if err != nil {
		return nil, err
	}
	model, err := transformer.TransformDSLToProto(string(source))
	if err != nil {
		return nil, fmt.Errorf("parsing %s: %w", path, err)
	}
	model.Id = authorisation.ModelID
	// The language transformer adds empty metadata to computed relations.
	// Omit those entries to preserve the prototype's persisted representation.
	for _, definition := range model.TypeDefinitions {
		for relation, metadata := range definition.GetMetadata().GetRelations() {
			if proto.Equal(metadata, &openfgav1.RelationMetadata{}) {
				delete(definition.Metadata.Relations, relation)
			}
		}
	}
	if _, err := typesystem.NewAndValidate(context.Background(), model); err != nil {
		return nil, fmt.Errorf("validating %s: %w", path, err)
	}
	return model, nil
}

// checkImmutableModel refuses changes to an already persisted model ID. The
// initial DSL must reproduce the original seed; later revisions need new IDs.
func checkImmutableModel(block []byte, model *openfgav1.AuthorizationModel) error {
	// SQL string literals escape apostrophes by doubling them. Only parse the
	// generated INSERT, leaving the surrounding schema and grant data alone.
	pattern := regexp.MustCompile(`(?s)INSERT INTO openfga_authorization_model\s*\(store_id,\s*model_id,\s*model\)\s*VALUES\s*\('((?:[^']|'')*)',\s*'((?:[^']|'')*)',\s*'((?:[^']|'')*)'\);`)
	matches := pattern.FindAllSubmatch(block, -1)
	if len(matches) != 1 {
		return fmt.Errorf("expected one authorisation model INSERT in generated block")
	}
	values := matches[0]
	if string(values[1]) != authorisation.StoreID {
		return fmt.Errorf("changing the authorisation store requires a migration")
	}
	var previous openfgav1.AuthorizationModel
	if err := protojson.Unmarshal([]byte(strings.ReplaceAll(string(values[3]), "''", "'")), &previous); err != nil {
		return fmt.Errorf("decoding previous authorisation model: %w", err)
	}
	if previous.Id != string(values[2]) {
		return fmt.Errorf("persisted authorisation model IDs disagree")
	}
	if previous.Id == model.Id && !proto.Equal(&previous, model) {
		return fmt.Errorf("authorisation model %s is immutable; add a new DSL version, model ID and schema migration", model.Id)
	}
	return nil
}

// canonicalJSON removes protobuf JSON's optional whitespace and sorts map keys
// so regeneration is reproducible without changing repeated-field ordering.
func canonicalJSON(model *openfgav1.AuthorizationModel) ([]byte, error) {
	data, err := (protojson.MarshalOptions{UseProtoNames: true}).Marshal(model)
	if err != nil {
		return nil, err
	}
	var value any
	decoder := json.NewDecoder(bytes.NewReader(data))
	decoder.UseNumber()
	if err := decoder.Decode(&value); err != nil {
		return nil, err
	}
	return json.Marshal(value)
}

func replaceFile(path string, data []byte) error {
	info, err := os.Stat(path)
	if err != nil {
		return err
	}
	file, err := os.CreateTemp(filepath.Dir(path), ".authorisation-*.sql.tmp")
	if err != nil {
		return err
	}
	defer os.Remove(file.Name())
	defer file.Close()
	if err := file.Chmod(info.Mode().Perm()); err != nil {
		return err
	}
	if _, err := file.Write(data); err != nil {
		return err
	}
	if err := file.Close(); err != nil {
		return err
	}
	return os.Rename(file.Name(), path)
}
